#!/usr/bin/env python3
"""Regenerate catalog.toml from every <plugin>/plugin.toml in this repo.

Noctalia refuses a git source without a catalog.toml at the repo root
("no catalog.toml in source"). Path sources don't need one. Run this after
adding a plugin or bumping a version, and commit the result:

    python3 scripts/update-catalog.py
"""

from __future__ import annotations

import json
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FIELDS = [
    "id",
    "name",
    "version",
    "author",
    "license",
    "icon",
    "description",
    "deprecated",
    "plugin_api",
    "tags",
    "dependencies",
]


def toml_value(value: object) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    if isinstance(value, list):
        return "[" + ", ".join(toml_value(v) for v in value) + "]"
    raise TypeError(f"unsupported catalog value: {value!r}")


def main() -> int:
    rows = []
    for manifest in sorted(ROOT.glob("*/plugin.toml")):
        data = tomllib.loads(manifest.read_text())
        plugin_dir = manifest.parent.name
        expected = data["id"].split("/", 1)[1]
        if plugin_dir != expected:
            print(f"{manifest}: directory must be named {expected!r}", file=sys.stderr)
            return 1
        data.setdefault("deprecated", False)
        rows.append(data)

    out = [
        "# Generated by scripts/update-catalog.py from each plugin's plugin.toml.",
        "# Noctalia reads this to list git-source plugins without a full clone.",
        "",
    ]
    for data in rows:
        out.append("[[plugin]]")
        for field in FIELDS:
            if field in data:
                out.append(f"{field} = {toml_value(data[field])}")
        out.append("")
    (ROOT / "catalog.toml").write_text("\n".join(out))
    print(f"catalog.toml: {len(rows)} plugin(s)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
